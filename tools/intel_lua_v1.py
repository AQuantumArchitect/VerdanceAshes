#!/usr/bin/env python3
"""Into BAR: the company's belief about the planned map, as a Lua table the mod can VFS.Include.

    singleplayer/verdance_ashes/generated/va_intel_current.lua   (+ outbox/va_intel_current.lua)

Source is `intent.intel` (verdance-intent-intel/0.1, perspective company) — belief, never truth.
The board (luaui/Include/va_board.lua, drawn by gui_verdance_minimap.lua) tints each zone by what the company believes
until line of sight replaces the belief with the ground. Written beside next_mission_intent.json
every time the intent is materialised; mirrored into the customer pack with va_current.lua.
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any, Dict, Optional

LUA_NAME = "va_intel_current.lua"


def _lua(v: Any, ind: int = 0) -> str:
    pad = "  " * ind
    if v is None:
        return "nil"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        if v != v or v in (float("inf"), float("-inf")):
            return "nil"
        return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return json.dumps(v, ensure_ascii=False)
    if isinstance(v, (list, tuple)):
        if not v:
            return "{}"
        return "{\n" + ",\n".join(pad + "  " + _lua(x, ind + 1) for x in v) + "\n" + pad + "}"
    if isinstance(v, dict):
        if not v:
            return "{}"
        rows = []
        for k, x in v.items():
            ks = str(k)
            key = ks if ks.isidentifier() and not ks.startswith("__") else f"[{json.dumps(ks, ensure_ascii=False)}]"
            rows.append(pad + "  " + key + " = " + _lua(x, ind + 1))
        return "{\n" + ",\n".join(rows) + "\n" + pad + "}"
    return json.dumps(str(v))


def intel_to_lua(intel: Dict[str, Any]) -> str:
    """Compact: zones as {zoneId = {ours={v,c,state}, held=..., strength=..., threat=..., label=...}}."""
    zones: Dict[str, Any] = {}
    for zid, z in (intel.get("zones") or {}).items():
        row: Dict[str, Any] = {"label": z.get("label")}
        for role in ("ours", "held", "strength", "threat"):
            r = z.get(role) or {}
            if not r:
                continue
            row[role] = {
                "v": None if r.get("value") is None else round(float(r["value"]), 3),
                "c": round(float(r.get("confidence") or 0.0), 3),
                "state": r.get("state") or "dark",
                "age": None if r.get("age_min") is None else round(float(r["age_min"]), 1),
                "src": r.get("source"),
            }
            if role == "held" and r.get("faction"):
                row[role]["faction"] = str(r["faction"])   # who we last SAW holding it (hub faction palette)
        zones[zid] = row
    out = {
        "schema": intel.get("schema") or "verdance-intent-intel/0.1",
        "perspective": intel.get("perspective") or "company",
        "mapId": intel.get("mapId"),
        "asOfMinute": intel.get("asOfMinute"),
        "zones": zones,
        "posted": intel.get("posted") or [],
        "frames": intel.get("frames") or [],
        "questions": intel.get("questions") or [],
    }
    head = ("-- GENERATED by tools/intel_lua_v1.py — the company's BELIEF about the planned map, not the truth.\n"
            "-- The HUD draws this until line of sight confirms or surprises it. Do not edit by hand.\n")
    return head + "return " + _lua(out) + "\n"


def write_intel_lua(intent: Dict[str, Any], workspace: Path) -> Dict[str, Any]:
    intel = intent.get("intel") if isinstance(intent, dict) else None
    if not isinstance(intel, dict):
        intel = {"schema": "verdance-intent-intel/0.1", "perspective": "company", "mapId": (intent or {}).get("mapId"), "zones": {}}
    text = intel_to_lua(intel)
    ws = Path(workspace)
    targets = [
        ws / "mod" / "VerdanceAshes.sdd" / "singleplayer" / "verdance_ashes" / "generated" / LUA_NAME,
        ws / "outbox" / LUA_NAME,
    ]
    written = []
    for t in targets:
        try:
            t.parent.mkdir(parents=True, exist_ok=True)
            t.write_text(text, encoding="utf-8")
            written.append(str(t))
        except Exception:
            pass
    return {"ok": bool(written), "written": written, "zones": len(intel.get("zones") or {})}


PAD_NAME = "va_pad_current.lua"


def pad_links(state: Dict[str, Any], workspace: Path, map_id: Optional[str], pad_zone: Optional[str]) -> list:
    """Where the company can extract TO from this pad: the camp (always), same-map zones we hold,
    and the zone graph's map links out of this map. Facts from the graph + our holdings; no truth
    about anyone else leaks in."""
    links: list = []
    if not pad_zone:
        return links
    try:
        g = json.loads((Path(workspace) / "data" / "zone_maps" / "world_zone_graph.v1.json").read_text(encoding="utf-8-sig"))
    except Exception:
        return links
    label = {n.get("zoneId"): n.get("label") for n in g.get("nodes") or []}
    node_map = {n.get("zoneId"): n.get("mapId") for n in g.get("nodes") or []}
    zm = (state.get("zoneMemory") or {}).get(map_id) or {}
    ours = {zid for zid, z in zm.items() if isinstance(z, dict) and str(z.get("controllingFaction") or "") == "ashwalkers"}
    seen = set()
    for e in g.get("edges") or []:
        a, b = str(e.get("from")), str(e.get("to"))
        if pad_zone not in (a, b):
            continue
        other = b if a == pad_zone else a
        if other in seen:
            continue
        kind = str(e.get("kind") or "same_map")
        if kind == "same_map":
            if other in ours:
                seen.add(other)
                links.append({"zoneId": other, "label": label.get(other, other), "mapId": node_map.get(other, map_id), "kind": "holding"})
        else:
            seen.add(other)
            links.append({"zoneId": other, "label": label.get(other, other), "mapId": node_map.get(other), "kind": "link"})
    return links


def write_pad_lua(intent: Dict[str, Any], state: Dict[str, Any], workspace: Path) -> Dict[str, Any]:
    """generated/va_pad_current.lua: the one landing/extraction point and its destinations.
    The exfil gadget reads it; the campaign gadget's deploy beacon, kit and extraction pad all
    resolve to the same zone, so this is the single point of truth for 'where we are'."""
    map_id = intent.get("mapId")
    zone = intent.get("deploymentZoneId")
    anchor = None
    try:
        zmap = json.loads((Path(workspace) / "data" / "zone_maps" / "authored" / f"{map_id}.authored.zone_map.json").read_text(encoding="utf-8-sig"))
        for z in zmap.get("zones") or []:
            if z.get("zoneId") == zone:
                a = z.get("anchor") or {}
                if a.get("x") is not None:
                    anchor = {"x": float(a["x"]), "z": float(a["z"])}
                else:
                    b = z.get("bounds") or {}
                    anchor = {"x": (float(b.get("xMin", 0)) + float(b.get("xMax", 0))) / 2, "z": (float(b.get("zMin", 0)) + float(b.get("zMax", 0))) / 2}
                break
    except Exception:
        pass
    pad = {"schema": "verdance-pad/1", "zoneId": zone, "mapId": map_id, "x": anchor and anchor["x"], "z": anchor and anchor["z"],
           "radius": 560, "links": pad_links(state, Path(workspace), map_id, zone)}
    text = "-- GENERATED by tools/intel_lua_v1.py — the pad: where the company lands and lifts, and where it can lift TO.\n" + "return " + _lua(pad) + "\n"
    ws = Path(workspace)
    written = []
    for t in (ws / "mod" / "VerdanceAshes.sdd" / "singleplayer" / "verdance_ashes" / "generated" / PAD_NAME, ws / "outbox" / PAD_NAME):
        try:
            t.parent.mkdir(parents=True, exist_ok=True)
            t.write_text(text, encoding="utf-8")
            written.append(str(t))
        except Exception:
            pass
    return {"ok": bool(written), "written": written, "pad": pad}


if __name__ == "__main__":
    import sys
    ws = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parents[1]
    intent = json.loads((ws / "outbox" / "next_mission_intent.json").read_text(encoding="utf-8-sig"))
    print(json.dumps(write_intel_lua(intent, ws), indent=2))
