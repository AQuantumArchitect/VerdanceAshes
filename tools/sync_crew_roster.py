#!/usr/bin/env python3
"""Write the M.HEROES table and M.BAND_ORDER of va_crew_roster.lua from data/story/crew_packs.json.

    python3 tools/sync_crew_roster.py          # rewrite in place
    python3 tools/sync_crew_roster.py --check  # exit 1 when the Lua is out of date

The JSON is the one source; the Lua carries only what the gadgets read. M.FACTORIES is written from
crew_packs "factories"; the rest of the file (helpers, MENTOR_PRODUCTS) is kept as it is.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PACKS = ROOT / "data" / "story" / "crew_packs.json"
LUA = ROOT / "mod" / "VerdanceAshes.sdd" / "luarules" / "gadgets" / "include" / "va_crew_roster.lua"

# Fields the gadgets read, in the order they are written.
FIELDS = ["name", "fieldName", "partners", "role", "unitDef", "hireTnb", "hireKm", "packTotal", "extras", "noTnbStake",
          "missionCritical", "canLead", "formation", "factory", "heroTrait", "fieldEffect", "deprecated", "startXp",
          "packMind", "tags", "escorts", "blurb"]


def lua_str(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua_val(v, ind: str) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, list):
        if all(isinstance(x, str) for x in v):
            return "{ " + ", ".join(lua_str(x) for x in v) + " }" if v else "{}"
        inner = ind + "  "
        out = "{\n"
        for x in v:
            out += inner + lua_val(x, inner) + ",\n"
        return out + ind + "}"
    if isinstance(v, dict):
        inner = ind + "  "
        out = "{\n"
        for k, x in v.items():
            out += f"{inner}{k} = {lua_val(x, inner)},\n"
        return out + ind + "}"
    return "nil"


def hero_block(hid: str, p: dict) -> str:
    out = f"  {hid} = {{\n"
    for k in FIELDS:
        if k not in p or p[k] is None:
            continue
        v = p[k]
        if k == "packMind" and not v:
            continue
        if k == "escorts":
            v = [{"unitDef": e["unitDef"], "count": e["count"]} for e in v]
        if k in ("noTnbStake",) and v is False:
            continue
        out += f"    {k} = {lua_val(v, '    ')},\n"
    return out + "  },\n"


def factories_block(fabs: dict) -> str:
    out = "M.FACTORIES = {\n"
    for k, f in fabs.items():
        out += f"  {k} = {{\n"
        for fk in ("structureDef", "boundHero", "product", "label", "startMetal", "repeatQueue"):
            if fk in f:
                out += f"    {fk} = {lua_val(f[fk], '    ') if f[fk] is not None else 'nil'},\n"
        out += "  },\n"
    return out + "}\n"


def render(src: str, packs: dict) -> str:
    heroes = packs["heroes"]
    order = list(packs.get("core") or []) + [h for h in heroes if h not in (packs.get("core") or [])]
    body = "M.HEROES = {\n" + "".join(hero_block(h, heroes[h]) for h in order if h in heroes) + "}\n"
    src = re.sub(r"M\.HEROES = \{\n.*?\n\}\n", lambda _: body, src, count=1, flags=re.S)
    src = re.sub(r"M\.FACTORIES = \{\n.*?\n\}\n", lambda _: factories_block(packs.get("factories") or {}), src, count=1, flags=re.S)
    band = [h for h in heroes if heroes[h].get("role") == "band"]
    lines, row = [], []
    for h in band:
        row.append(f'"{h}"')
        if len(row) == 10:
            lines.append("  " + ", ".join(row) + ","); row = []
    if row:
        lines.append("  " + ", ".join(row) + ",")
    src = re.sub(r"M\.BAND_ORDER = \{\n.*?\n\}\n", lambda _: "M.BAND_ORDER = {\n" + "\n".join(lines) + "\n}\n", src, count=1, flags=re.S)
    return src.replace("-- GENERATED by tools/sync_crew_packs_v1.py", "-- GENERATED by tools/sync_crew_roster.py")


def main() -> int:
    packs = json.loads(PACKS.read_text(encoding="utf-8-sig"))
    src = LUA.read_text(encoding="utf-8")
    new = render(src, packs)
    if "--check" in sys.argv:
        return 0 if new == src else 1
    LUA.write_text(new, encoding="utf-8")
    print(f"{len(packs['heroes'])} heroes -> {LUA.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
