#!/usr/bin/env python3
"""Hero Codex — sortable character DB, cross-charts, apply voice + doctrine.

SSOT: data/story/hero_codex.json
  list / chart / diffuse-check / apply / csv

Packs stay mass/kit. Roster stays campaign XP/recruit.
Codex owns character voice, position typing, and AI doctrine intent.
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
from collections import defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
CODEX_PATH = ROOT / "data" / "story" / "hero_codex.json"
CREW_JSON = ROOT / "data" / "story" / "crew_packs.json"
ROSTER_JSON = ROOT / "data" / "story" / "hero_roster.json"
DOCTRINE_LUA = (
    ROOT
    / "mod"
    / "VerdanceAshes.sdd"
    / "luarules"
    / "gadgets"
    / "include"
    / "va_hero_doctrine.lua"
)
CHART_MD = ROOT / "docs" / "HERO_CODEX_CHART.md"


def load_codex(path: Path = CODEX_PATH) -> Dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8-sig"))


def heroes(codex: Dict[str, Any]) -> List[Dict[str, Any]]:
    return [h for h in (codex.get("heroes") or []) if isinstance(h, dict) and h.get("heroId")]


def filter_heroes(
    rows: List[Dict[str, Any]],
    *,
    position: Optional[str] = None,
    tag: Optional[str] = None,
    doctrine: Optional[str] = None,
) -> List[Dict[str, Any]]:
    out = []
    for h in rows:
        if position and str(h.get("position") or "") != position:
            continue
        if doctrine and str(h.get("doctrine") or "") != doctrine:
            continue
        if tag:
            temps = [str(t) for t in (h.get("temperament") or [])]
            if tag not in temps:
                continue
        out.append(h)
    return out


def cmd_list(args: argparse.Namespace) -> int:
    codex = load_codex()
    rows = filter_heroes(
        heroes(codex),
        position=args.position,
        tag=args.tag,
        doctrine=args.doctrine,
    )
    if args.csv:
        w = csv.writer(sys.stdout)
        w.writerow(
            [
                "heroId",
                "name",
                "position",
                "combatVerb",
                "temperament",
                "doctrine",
                "preferDefenses",
                "allowBail",
                "allowKite",
                "hook",
                "faction",
                "unitDef",
            ]
        )
        for h in rows:
            w.writerow(
                [
                    h.get("heroId"),
                    h.get("name"),
                    h.get("position"),
                    h.get("combatVerb"),
                    "|".join(h.get("temperament") or []),
                    h.get("doctrine"),
                    h.get("preferDefenses"),
                    h.get("allowBail"),
                    h.get("allowKite"),
                    (h.get("voice") or {}).get("hook"),
                    h.get("faction"),
                    h.get("unitDef"),
                ]
            )
        return 0
    for h in rows:
        voice = h.get("voice") or {}
        tags = ",".join(h.get("temperament") or [])
        print(
            f"{h.get('heroId'):12} {h.get('position'):12} {h.get('doctrine'):12} "
            f"verb={h.get('combatVerb'):8} [{tags}]  {voice.get('hook')}"
        )
    print(f"# {len(rows)} heroes")
    return 0


def build_matrix(rows: List[Dict[str, Any]], vocab: List[str], positions: List[str]) -> Dict[str, Dict[str, List[str]]]:
    matrix: Dict[str, Dict[str, List[str]]] = {
        p: {t: [] for t in vocab} for p in positions
    }
    for h in rows:
        pos = str(h.get("position") or "")
        if pos not in matrix:
            matrix[pos] = {t: [] for t in vocab}
        for t in h.get("temperament") or []:
            ts = str(t)
            matrix[pos].setdefault(ts, []).append(str(h.get("heroId")))
    return matrix


def matrix_markdown(codex: Dict[str, Any]) -> str:
    rows = heroes(codex)
    vocab = list(codex.get("temperamentVocab") or [])
    positions = list(codex.get("positions") or [])
    matrix = build_matrix(rows, vocab, positions)
    lines = [
        "# Hero Codex — position × temperament",
        "",
        "_Generated by `tools/hero_codex_v1.py chart`. SSOT: `data/story/hero_codex.json`._",
        "",
        "| position | " + " | ".join(vocab) + " |",
        "|---|" + "|".join(["---"] * len(vocab)) + "|",
    ]
    for pos in positions:
        cells = []
        for t in vocab:
            ids = matrix.get(pos, {}).get(t) or []
            cells.append(", ".join(ids) if ids else "")
        lines.append(f"| **{pos}** | " + " | ".join(cells) + " |")
    lines.extend(["", "## Hooks", ""])
    for h in rows:
        voice = h.get("voice") or {}
        lines.append(
            f"- **{h.get('name')}** (`{h.get('heroId')}`) — _{voice.get('hook')}_ "
            f"[{h.get('position')} / {h.get('doctrine')} / {h.get('combatVerb')}]"
        )
    lines.append("")
    return "\n".join(lines)


def cmd_chart(args: argparse.Namespace) -> int:
    codex = load_codex()
    md = matrix_markdown(codex)
    if args.write:
        CHART_MD.parent.mkdir(parents=True, exist_ok=True)
        CHART_MD.write_text(md, encoding="utf-8")
        print(f"wrote {CHART_MD}")
    print(md)
    return 0


def cmd_diffuse_check(args: argparse.Namespace) -> int:
    """Flag heroes that share position + identical temperament set (unordered)."""
    rows = heroes(load_codex())
    by_key: Dict[str, List[str]] = defaultdict(list)
    hooks: Dict[str, List[str]] = defaultdict(list)
    for h in rows:
        temps = tuple(sorted(str(t) for t in (h.get("temperament") or [])))
        key = f"{h.get('position')}|{'+'.join(temps)}"
        by_key[key].append(str(h.get("heroId")))
        hook = str((h.get("voice") or {}).get("hook") or "").strip().lower()
        if hook:
            hooks[hook].append(str(h.get("heroId")))
    bad = 0
    print("## Same position + same temperament set")
    for key, ids in sorted(by_key.items()):
        if len(ids) > 1:
            bad += 1
            print(f"  COLLISION {key}: {ids}")
    if bad == 0:
        print("  (none — clusters may share a tag but not the full set)")
    print("## Duplicate hooks")
    dups = {h: ids for h, ids in hooks.items() if len(ids) > 1}
    if not dups:
        print("  (none)")
    else:
        for h, ids in dups.items():
            bad += 1
            print(f"  DUP hook {h!r}: {ids}")
    print("## Multi-occupant single-tag cells (expected clusters)")
    codex = load_codex()
    matrix = build_matrix(
        rows,
        list(codex.get("temperamentVocab") or []),
        list(codex.get("positions") or []),
    )
    for pos, tags in matrix.items():
        for t, ids in tags.items():
            if len(ids) > 1:
                print(f"  {pos} × {t}: {ids}")
    return 1 if dups else 0


def _lua_bool(v: Any) -> str:
    return "true" if v else "false"


def emit_doctrine_lua(rows: List[Dict[str, Any]]) -> str:
    lines = [
        "-- Verdance hero doctrine map (GENERATED by tools/hero_codex_v1.py apply).",
        "-- Character SSOT: data/story/hero_codex.json — do not hand-edit.",
        "",
        "local M = {}",
        "",
        "M.HERO_DOCTRINE = {",
    ]
    for h in rows:
        hid = str(h.get("heroId"))
        kind = str(h.get("doctrine") or "default")
        lines.append(
            f"  {hid} = {{"
            f" kind = \"{kind}\","
            f" preferDefenses = {_lua_bool(h.get('preferDefenses'))},"
            f" allowBail = {_lua_bool(h.get('allowBail'))},"
            f" allowKite = {_lua_bool(h.get('allowKite'))},"
            f" verb = \"{h.get('combatVerb')}\","
            f" }},"
        )
    lines.extend(
        [
            "}",
            "",
            "function M.forHero(heroId)",
            "  heroId = tostring(heroId or \"\")",
            "  return M.HERO_DOCTRINE[heroId]",
            "end",
            "",
            "return M",
            "",
        ]
    )
    return "\n".join(lines)


def position_to_role_spread(rows: List[Dict[str, Any]]) -> Dict[str, List[str]]:
    spread: Dict[str, List[str]] = {
        "core": [],
        "eco": [],
        "eyes": [],
        "line": [],
        "skirmish": [],
        "siege": [],
        "shield": [],
        "deprecated": [],
        "reserved": [],
    }
    for h in rows:
        hid = str(h.get("heroId"))
        pos = str(h.get("position") or "")
        if pos == "core_skirm" or pos == "core_rez":
            spread["core"].append(hid)
        elif pos in spread:
            spread[pos].append(hid)
    return spread


def cmd_apply(args: argparse.Namespace) -> int:
    codex = load_codex()
    rows = heroes(codex)
    by_id = {str(h["heroId"]): h for h in rows}

    packs = json.loads(CREW_JSON.read_text(encoding="utf-8-sig"))
    ph = packs.setdefault("heroes", {})
    for hid, row in by_id.items():
        if hid not in ph or not isinstance(ph[hid], dict):
            continue
        voice = row.get("voice") or {}
        ph[hid]["name"] = row.get("name") or ph[hid].get("name")
        if voice.get("blurb"):
            ph[hid]["blurb"] = voice["blurb"]
    packs["roleSpread"] = position_to_role_spread(rows)
    notes = str(packs.get("notes") or "")
    marker = "Character SSOT: data/story/hero_codex.json"
    if marker not in notes:
        packs["notes"] = (notes + " " + marker).strip()
    CREW_JSON.write_text(json.dumps(packs, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"updated {CREW_JSON}")

    if ROSTER_JSON.is_file():
        roster = json.loads(ROSTER_JSON.read_text(encoding="utf-8-sig"))
        rheroes = roster.get("heroes") or []
        seen = set()
        for h in rheroes:
            if not isinstance(h, dict):
                continue
            hid = str(h.get("heroId") or "")
            seen.add(hid)
            row = by_id.get(hid)
            if not row:
                continue
            voice = row.get("voice") or {}
            h["name"] = row.get("name") or h.get("name")
            if voice.get("fiction"):
                h["fiction"] = voice["fiction"]
            if row.get("unitDef"):
                h["unitDef"] = row["unitDef"]
        # Ensure core + new band fiction exists even if roster omitted them historically.
        # Pavise replaced Vane as left hand; Halbard is the corhal band hire.
        ensure_ids = (
            ("pavise", {"type": "core"}, 0.45, 40.0),
            ("ketha", {"type": "core"}, 0.06, 0.0),
            ("halbard", {"type": "band"}, 0.08, 0.0),
        )
        for hid, recruit, start_xp, camp_xp in ensure_ids:
            if hid in seen or hid not in by_id:
                continue
            row = by_id[hid]
            voice = row.get("voice") or {}
            rheroes.append(
                {
                    "heroId": hid,
                    "name": row.get("name"),
                    "unitDef": row.get("unitDef"),
                    "missionCritical": hid == "ketha",
                    "status": "active",
                    "xp": float(start_xp),
                    "timesWounded": 0,
                    "campaignXp": float(camp_xp),
                    "peakBarXp": float(start_xp),
                    "trait": (row.get("temperament") or ["core"])[0],
                    "traits": list(row.get("temperament") or []),
                    "fiction": voice.get("fiction"),
                    "recruit": dict(recruit),
                }
            )
            seen.add(hid)
        roster["heroes"] = rheroes
        roster["notes"] = (
            "Named-hero roster. Voice/fiction from hero_codex.json (apply). "
            "Core pavise+ketha always ship; Halbard band on corhal."
        )
        ROSTER_JSON.write_text(
            json.dumps(roster, indent=2, ensure_ascii=False) + "\n", encoding="utf-8"
        )
        print(f"updated {ROSTER_JSON}")

    DOCTRINE_LUA.parent.mkdir(parents=True, exist_ok=True)
    DOCTRINE_LUA.write_text(emit_doctrine_lua(rows), encoding="utf-8")
    print(f"wrote {DOCTRINE_LUA}")

    if args.chart:
        CHART_MD.parent.mkdir(parents=True, exist_ok=True)
        CHART_MD.write_text(matrix_markdown(codex), encoding="utf-8")
        print(f"wrote {CHART_MD}")

    if args.sync:
        import subprocess

        sync = ROOT / "tools" / "sync_crew_packs_v1.py"
        subprocess.check_call([sys.executable, str(sync)])
        print("synced crew packs")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    sp = ap.add_subparsers(dest="cmd", required=True)

    p_list = sp.add_parser("list", help="List heroes (filterable)")
    p_list.add_argument("--position")
    p_list.add_argument("--tag")
    p_list.add_argument("--doctrine")
    p_list.add_argument("--csv", action="store_true")
    p_list.set_defaults(func=cmd_list)

    p_chart = sp.add_parser("chart", help="Print position × temperament matrix")
    p_chart.add_argument("--write", action="store_true", help=f"Also write {CHART_MD}")
    p_chart.set_defaults(func=cmd_chart)

    p_diff = sp.add_parser("diffuse-check", help="Flag hook/temperament collisions")
    p_diff.set_defaults(func=cmd_diffuse_check)

    p_apply = sp.add_parser("apply", help="Write voice + doctrine into packs/roster/lua")
    p_apply.add_argument("--sync", action="store_true", help="Run sync_crew_packs_v1 after")
    p_apply.add_argument("--chart", action="store_true", help="Write chart markdown")
    p_apply.set_defaults(func=cmd_apply)

    args = ap.parse_args()
    return int(args.func(args) or 0)


if __name__ == "__main__":
    raise SystemExit(main())
